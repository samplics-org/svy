"""Write the reference page of every error and warning code, read from svy's source.

Sections follow the groups in ``svy/errors/_codes.py``; each row's class, message and
hint come from the call that raises the code (``{...}`` in an f-string shows as ``…``).

    uv run python scripts/render_codes.py PATH            # write the page
    uv run python scripts/render_codes.py PATH --check    # exit 1 if PATH is stale
"""

from __future__ import annotations

import argparse
import ast
import re
import sys

from dataclasses import dataclass, field
from pathlib import Path


SRC = Path(__file__).resolve().parents[1] / "src" / "svy"
CODES_FILE = SRC / "errors" / "_codes.py"

_HEADER = """---
title: "Error and warning codes"
description: "Every code an svy error or warning carries, with the class it is raised as."
format:
  html:
    toc: true
    toc-depth: 2
---

<!-- Generated by svy's scripts/render_codes.py; edit the source, not this page. -->

Every svy error and warning carries a code, listed in `svy.errors.Code`. The class names
the part of svy that raised it, and each error is also a Python builtin:
`except svy.errors.ModelError`, `except ValueError` and `except svy.SvyError` all catch
`ModelError.ValueError`. Warnings are filtered by their class,
`warnings.filterwarnings("ignore", category=svy.errors.WeightingWarning)`, or by code,
`warnings.filterwarnings("ignore", message=r"\\[GLM_SEPARATION\\]")`.
"""


@dataclass
class Entry:
    code: str
    area: str
    raised_as: set[str] = field(default_factory=set)
    title: str = ""
    hint: str = ""


def anchor(code: str) -> str:
    return code.lower().replace("_", "-")


def _groups() -> dict[str, str]:
    """Each code's section title, from the comment heading its group in _codes.py."""
    out: dict[str, str] = {}
    section = ""
    for line in CODES_FILE.read_text().splitlines():
        head = re.match(r"\s*# ── (.+?) ─", line)
        if head:
            section = head.group(1).split(":")[0]
        member = re.match(r'    ([A-Z][A-Z0-9_]+) = "', line)
        if member:
            out[member.group(1)] = section
    return out


def _text(node: ast.expr | None) -> str:
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    if isinstance(node, ast.JoinedStr):
        return "".join(v.value if isinstance(v, ast.Constant) else "…" for v in node.values)
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        return _text(node.left) + _text(node.right)
    return ""


def _raised_as(call: ast.Call, cls: str | None) -> str:
    func = call.func
    name = (
        func.id
        if isinstance(func, ast.Name)
        else f"{getattr(func.value, 'id', '')}.{func.attr}"
        if isinstance(func, ast.Attribute)
        else ""
    )
    head, _, tail = name.partition(".")
    if head == "cls" or name in ("cls", "kind"):
        owner = "<Area>Error" if cls == "_Constructors" else cls or ""
        return f"{owner}.{tail}" if tail and tail[0].isupper() else owner
    if re.fullmatch(r"\w+(Error|Warning)", head):
        return name if tail and tail[0].isupper() else head
    if name == "_finding":
        return "SelectionWarning"
    if name == "template_levels":
        return "WeightingError.ValueError"
    return ""


def _code_refs(node: ast.AST) -> list[str]:
    return [
        n.attr
        for n in ast.walk(node)
        if isinstance(n, ast.Attribute) and getattr(n.value, "id", "") == "Code"
    ]


def _defaults(tree: ast.Module, entries: dict[str, Entry]) -> None:
    """A class's ``_DEFAULT_CODE`` (or ``code`` default) is what it carries without a code."""
    for cls in [n for n in ast.walk(tree) if isinstance(n, ast.ClassDef)]:
        for stmt in cls.body:
            if isinstance(stmt, ast.AnnAssign) and stmt.value is not None:
                if getattr(stmt.target, "id", "") in ("_DEFAULT_CODE", "code"):
                    for code in _code_refs(stmt.value):
                        entries[code].raised_as.add(cls.name)
                        entries[code].title = entries[code].title or "No code given"


def collect(src: Path = SRC) -> dict[str, Entry]:
    groups = _groups()
    entries = {code: Entry(code, area) for code, area in groups.items()}
    for path in sorted(src.rglob("*.py")):
        tree = ast.parse(path.read_text())
        parents = {c: n for n in ast.walk(tree) for c in ast.iter_child_nodes(n)}
        _defaults(tree, entries)
        # Codes kept in a table reach their raise through a variable: credit them
        # to this module's calls that take a computed code.
        tabled = [
            code
            for n in ast.walk(tree)
            if isinstance(n, (ast.Tuple, ast.Dict))
            for code in _code_refs(n)
        ]
        computed: list[tuple[str, str, str]] = []
        for node in ast.walk(tree):
            if not isinstance(node, ast.Call):
                continue
            kw = {k.arg: k.value for k in node.keywords if k.arg}
            if "code" not in kw:
                continue
            owner = node
            while owner in parents and not isinstance(owner, ast.ClassDef):
                owner = parents[owner]
            cls = owner.name if isinstance(owner, ast.ClassDef) else None
            raised = _raised_as(node, cls)
            title, hint = _text(kw.get("title")), _text(kw.get("hint"))
            codes = _code_refs(kw["code"])
            if not codes:
                computed.append((raised, title, hint))
            for code in codes:
                entry = entries[code]
                if raised:
                    entry.raised_as.add(raised)
                entry.title = entry.title or title
                entry.hint = entry.hint or hint
        for code in tabled:
            entry = entries[code]
            for raised, title, hint in computed:
                if raised:
                    entry.raised_as.add(raised)
                entry.title = entry.title or title
                entry.hint = entry.hint or hint
    return entries


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def render(entries: dict[str, Entry]) -> str:
    sections: dict[str, list[Entry]] = {}
    for entry in entries.values():
        sections.setdefault(entry.area, []).append(entry)
    out = [_HEADER]
    for area, rows in sections.items():
        out += [
            f"\n## {area} {{#area-{anchor(area.split()[0])}}}\n",
            "| Code | Raised as | Message | Hint |",
            "|---|---|---|---|",
        ]
        for e in sorted(rows, key=lambda r: r.code):
            raised = ", ".join(f"`{r}`" for r in sorted(e.raised_as))
            out.append(
                f'| <span id="{anchor(e.code)}">`{e.code}`</span> | {raised} '
                f"| {_cell(e.title)} | {_cell(e.hint)} |"
            )
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("path", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    page = render(collect())
    if args.check:
        current = args.path.read_text() if args.path.exists() else ""
        if current != page:
            print(f"{args.path} is stale; rerun scripts/render_codes.py", file=sys.stderr)
            return 1
        return 0
    args.path.write_text(page)
    return 0


if __name__ == "__main__":
    sys.exit(main())
